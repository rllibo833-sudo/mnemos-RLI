const assert = require("node:assert/strict");
global.window = global;
require("./symbolic.js");
const S = global.BeyondLightSymbolic;
assert.equal(S.evaluate(S.parse("3*x^2 + 2*x + 1"), {x:2}), 17);
assert.equal(S.print(S.parse("x + 0")), "x");
assert.equal(S.evaluate(S.derivative(S.parse("x^3"), "x"), {x:2}), 12);
assert.equal(S.evaluate(S.integrate(S.parse("x^2"), "x"), {x:2}), 8/3);
assert.throws(() => S.evaluate(S.parse("x/0"), {x:1}), /nol/);
assert.throws(() => S.parse("tan(x)"), /Fungsi tidak didukung/);
assert.throws(() => S.parse("x;alert(1)"), /Karakter tidak dikenal/);
assert.throws(() => S.evaluate(S.parse("unknown"), {}), /belum diberi nilai/);
assert.equal(S.substitute("x+y","x","2"),"(2+y)");
assert.equal(S.isolate("2*x+3","11","x"),"4");
assert.equal(S.isolate("10/x","2","x"),"5");
assert.equal(S.isolate("sqrt(x)","3","x"),"9");
assert.throws(()=>S.isolate("x+1","x-1","x"),/tepat pada satu sisi/);
assert.throws(()=>S.isolate("x^y","8","x"),/eksponen variabel/);
console.log("symbolic browser engine: substitution and bounded isolation checks passed");
